def sha(path):
 h=hashlib.sha256()
 with path.open('rb') as f:
  for b in iter(lambda:f.read(8*1024*1024),b''):h.update(b)
 return h.hexdigest()
def write_json(path,data):
 tmp=path.with_suffix(path.suffix+'.partial');tmp.write_text(json.dumps(data,indent=2)+'\n');tmp.replace(path)
def repack(source,name,version,module,provenance):
 dist=f'{name.replace("-","_")}-{version}.dist-info'
 record=source/dist/'RECORD'
 if not record.is_file():raise ValueError('Missing RECORD: '+name)
 rows=list(csv.reader(record.open(newline='')))
 if any(len(r)!=3 for r in rows) or len({r[0] for r in rows})!=len(rows):raise ValueError('Invalid or duplicate RECORD entries')
 meta=Parser().parsestr((source/dist/'METADATA').read_text())
 if meta['Name'].lower().replace('_','-')!=name or meta['Version']!=version:raise ValueError('Wrong package identity')
 wheel=Parser().parsestr((source/dist/'WHEEL').read_text())
 tags=wheel.get_all('Tag',[])
 tag_parts=[x.split('-') for x in tags]
 if not tags or any(len(x)!=3 or x[0]!='py3' or x[1]!='none' for x in tag_parts):raise ValueError('Expected Python-independent NVIDIA wheel tags')
 groups=[list(dict.fromkeys(x[i] for x in tag_parts)) for i in range(3)]
 if set('-'.join(x) for x in itertools.product(*groups))!=set(tags):raise ValueError('Tags cannot be collapsed safely')
 filename=f'{name.replace("-","_")}-{version}-'+ '-'.join('.'.join(g) for g in groups)+'.whl'
 target=OUT/filename;partial=OUT/(filename+'.partial')
 if target.exists():raise FileExistsError(target)
 report={'package':name,'version':version,'source':provenance,'source_record_sha256':sha(record),'wheel_tags':tags,'record_verified_files':[],'excluded_installation_files':[],'status':'FAIL'}
 new_rows=[];size_total=0
 try:
  with zipfile.ZipFile(partial,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=1,allowZip64=True) as z:
   for path,hashspec,length in rows:
    pp=PurePosixPath(path)
    if pp.is_absolute() or '..' in pp.parts:raise ValueError('Unsafe RECORD path: '+path)
    if path==dist+'/RECORD':
     if hashspec or length:raise ValueError('RECORD self-entry must be unhashed')
     continue
    if path.endswith('.pyc') or '__pycache__' in pp.parts:
     report['excluded_installation_files'].append({'path':path,'reason':'generated bytecode excluded; not wheel payload'});continue
    if not (path.startswith('nvidia/'+module+'/') or path.startswith(dist+'/') or path=='nvidia/__init__.py'):
     raise ValueError('Unexpected package payload path: '+path)
    p=source/path
    if not p.is_file() or p.is_symlink() or not p.resolve().is_relative_to(source.resolve()):raise ValueError('Missing/nonregular source: '+path)
    generated=path.rsplit('/',1)[-1] in {'INSTALLER','REQUESTED','direct_url.json'} or path.endswith('.pyc') or '__pycache__' in pp.parts
    if not hashspec or not length:
     if generated and (path.endswith('.pyc') or '__pycache__' in pp.parts):
      report['excluded_installation_files'].append({'path':path,'reason':'unhashed generated bytecode'});continue
     raise ValueError('Missing payload hash/size: '+path)
    algorithm,expected=hashspec.split('=',1)
    if algorithm not in {'sha256','sha384','sha512'}:raise ValueError('Weak/unrecognized hash: '+path)
    h=hashlib.new(algorithm);actual_sha=hashlib.sha256();count=0
    zi=zipfile.ZipInfo(path,date_time=(1980,1,1,0,0,0));zi.create_system=3
    zi.external_attr=(stat.S_IMODE(p.stat().st_mode)&0o777|stat.S_IFREG)<<16
    zi.compress_type=zipfile.ZIP_DEFLATED;zi._compresslevel=1
    zout=None if generated else z.open(zi,'w',force_zip64=True)
    try:
     with p.open('rb') as src:
      for b in iter(lambda:src.read(8*1024*1024),b''):
       h.update(b);actual_sha.update(b);count+=len(b)
       if zout:zout.write(b)
    finally:
     if zout:zout.close()
    actual=base64.urlsafe_b64encode(h.digest()).rstrip(b'=').decode()
    if actual!=expected or count!=int(length):raise ValueError('RECORD hash/size mismatch: '+path)
    report['record_verified_files'].append({'path':path,'sha256':actual_sha.hexdigest(),'size_bytes':count})
    if generated:report['excluded_installation_files'].append({'path':path,'reason':'verified installed metadata; excluded from rebuilt wheel'})
    else:
     new_rows.append((path,'sha256='+base64.urlsafe_b64encode(actual_sha.digest()).rstrip(b'=').decode(),str(count)));size_total+=count
   if not any(r[0]==dist+'/METADATA' for r in new_rows) or not any(r[0]==dist+'/WHEEL' for r in new_rows):raise ValueError('Incomplete RECORD: required metadata absent')
   text=io.StringIO(newline='');writer=csv.writer(text,lineterminator='\n');writer.writerows(new_rows);writer.writerow((dist+'/RECORD','',''))
   z.writestr(dist+'/RECORD',text.getvalue())
  # Read every rebuilt member and compare the new RECORD before publication.
  with zipfile.ZipFile(partial) as z:
   rebuilt=list(csv.reader(io.TextIOWrapper(z.open(dist+'/RECORD'),encoding='utf-8',newline='')))
   if set(z.namelist())!={x[0] for x in rebuilt}:raise ValueError('Unrecorded or absent wheel members')
   for path,hs,sz in rebuilt:
    if not hs:continue
    h=hashlib.sha256();count=0
    with z.open(path) as f:
     for b in iter(lambda:f.read(8*1024*1024),b''):h.update(b);count+=len(b)
    if 'sha256='+base64.urlsafe_b64encode(h.digest()).rstrip(b'=').decode()!=hs or str(count)!=sz:raise ValueError('Rebuilt wheel integrity failure')
  wheel_sha=sha(partial);size=partial.stat().st_size
  report.update(status='PASS',filename=filename,wheel_sha256=wheel_sha,wheel_size_bytes=size,payload_size_bytes=size_total,checked_at_utc=datetime.now(timezone.utc).isoformat())
  partial.replace(target)
  write_json(LOG/(name+'-'+version+'.json'),report)
  print('VERIFIED',name,version,size,wheel_sha,flush=True)
  return report
 except Exception as e:
  report['error']=str(e);write_json(LOG/(name+'-'+version+'.json'),report)
  partial.unlink(missing_ok=True)
  raise

def publish_manifest():
 reports=[]
 for p in LOG.glob('nvidia-*.json'):
  d=json.loads(p.read_text())
  if d.get('status')=='PASS':reports.append(d)
 reports.sort(key=lambda x:x['filename'])
 manifest={'scope':'Repacked installed NVIDIA package payload; not original upstream wheel archive hashes','packages':[{k:v for k,v in r.items() if k!='record_verified_files'} for r in reports]}
 write_json(OUT/'REPACKED-SOURCES.json',manifest)
 (OUT/'REPACKED-SHA256SUMS').write_text(''.join(r['wheel_sha256']+'  '+r['filename']+'\n' for r in reports))
 write_json(LOG/'summary.json',{'status':'PASS' if len(reports)==14 else 'IN_PROGRESS','verified_packages':len(reports),'wheel_bytes':sum(r['wheel_size_bytes'] for r in reports)})

if __name__=='__main__':
 mode=sys.argv[1]
